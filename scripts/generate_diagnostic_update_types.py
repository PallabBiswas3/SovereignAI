"""Generate the frontend type from the diagnostic service's response schema."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "Time-Series-Diagnostic-Agent" / "src"))
from tsdiag.runtime_updates import DiagnosticUpdate


def typescript(schema):
    if "anyOf" in schema:
        return " | ".join(typescript(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if schema.get("type") == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(map(typescript, schema["prefixItems"])) + "]"
        return f"Array<{typescript(schema.get('items', {}))}>"
    return {"string": "string", "number": "number", "integer": "number",
            "boolean": "boolean", "null": "null", "object": "Record<string, unknown>"}.get(schema.get("type"), "unknown")


def generated_type():
    schema = DiagnosticUpdate.model_json_schema()
    required = schema.get("required", [])
    fields = [f"  {key}{'' if key in required else '?'}: {typescript(value)};" for key, value in schema["properties"].items()]
    return "// Generated by scripts/generate_diagnostic_update_types.py; do not edit.\nexport type DiagnosticUpdate = {\n" + "\n".join(fields) + "\n};\n"


if __name__ == "__main__":
    path = ROOT / "frontend" / "lib" / "diagnostic-update.ts"
    if "--check" in sys.argv:
        if not path.is_file() or path.read_text(encoding="utf-8") != generated_type():
            raise SystemExit("Diagnostic update types are stale; regenerate them.")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(generated_type(), encoding="utf-8")
